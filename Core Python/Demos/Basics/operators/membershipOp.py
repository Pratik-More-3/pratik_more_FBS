#1. in : It checks if a value is present in a sequence.

print('f' in 'Firstbit') # False
print('F' in 'Firstbit') # True
print(3 in [1, 2, 3, 4, 5])  # True
print(6 in [1, 2, 3, 4, 5])  # False

#2. not in : It checks if a value is not present in a sequence.

print('f' not in 'Firstbit') # True
print('F' not in 'Firstbit') # False
print(3 not in [1, 2, 3, 4, 5])  # False
print(6 not in [1, 2, 3, 4, 5])  # True