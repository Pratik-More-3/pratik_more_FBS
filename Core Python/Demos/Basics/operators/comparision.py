### Comparison Operators Rationale operators are used to compare two values. The result of a comparison is a boolean value: True or False.
x = 10
y = 20
a = 'abc'

#1. ==  # Exact equals to
print(x == y)      # False
print(x == '10')   # False

#2. !=  # Not equals to
print(x != y)      # True

#3. >  # Greater than
print(x > 5)       # True

#4. >=  # Greater than or equals to
print(x >= 10)     # True

#5. <  # Less than
print(x < y)       # True
print(x < 10)      # False

#6. <=  # Less than or equals to
print(x <= 10)     # True
